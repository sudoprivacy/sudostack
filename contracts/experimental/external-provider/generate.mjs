import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { basename, dirname, join, resolve } from 'node:path'
import { readLocalGitBlob, requireFullCommitSha, sha256 } from '../../../tools/contracts/source.mjs'

export function validateExternalLock(lock) {
  requireFullCommitSha(lock.revision, 'Moss external-provider revision')
  if (lock.repository !== 'https://github.com/sudoprivacy/moss' || lock.semanticOwner !== 'moss' || lock.maturity !== 'experimental-synthetic-pilot' || lock.path !== 'contracts/external-provider/v1/contract.ts' || !/^sha256:[a-f0-9]{64}$/.test(lock.digest)) throw new Error('Invalid experimental source identity')
}
export function renderExternalContract(lock, source) {
  validateExternalLock(lock)
  if (source.includes('\r') || !source.endsWith('\n')) throw new Error('Owner source must use LF with a final newline')
  if (`sha256:${sha256(source)}` !== lock.digest) throw new Error('Semantic owner content digest mismatch')
  return `// Derived from Moss ${lock.revision}:${lock.path}. DO NOT EDIT.\n${source}`
}
export function generateExternalContract(owner, check = false) {
  const root = dirname(fileURLToPath(import.meta.url))
  const lock = JSON.parse(readFileSync(join(root, 'source.lock.json'), 'utf8'))
  validateExternalLock(lock)
  const priorRoot = process.env.SUDOSTACK_REPOS_ROOT
  try {
    process.env.SUDOSTACK_REPOS_ROOT = dirname(resolve(owner))
    const source = readLocalGitBlob({ ...lock, checkout: basename(resolve(owner)) }, lock.path).toString('utf8')
    const output = renderExternalContract(lock, source), target = join(root, 'contract.gen.ts')
    if (check) {
      if (readFileSync(target, 'utf8') !== output) throw new Error('Generated experimental contract is stale')
    } else writeFileSync(target, output)
  } finally {
    if (priorRoot === undefined) delete process.env.SUDOSTACK_REPOS_ROOT
    else process.env.SUDOSTACK_REPOS_ROOT = priorRoot
  }
}
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2), owner = args[args.indexOf('--owner') + 1]
  if (!args.includes('--owner') || !owner) throw new Error('Pass --owner <Moss checkout>; reads the pinned commit, never the working tree')
  generateExternalContract(owner, args.includes('--check'))
  console.log('Experimental external-provider source identity, revision and generated bytes verified')
}
