import { readFileSync, writeFileSync } from 'node:fs'
import { basename, dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { readLocalGitBlob, requireFullCommitSha, sha256 } from '../../../tools/contracts/source.mjs'

const root = dirname(fileURLToPath(import.meta.url))
const files = {
  "contracts/agent-catalog/v1alpha1/contract.ts": "contract.gen.ts",
  "contracts/agent-catalog/v1alpha1/schema.json": "schema.gen.json"
}

export function validateCatalogLock(lock) {
  requireFullCommitSha(lock.revision, 'Moss agent-catalog revision')
  if (lock.repository !== 'https://github.com/sudoprivacy/moss' || lock.semanticOwner !== 'moss'
    || lock.maturity !== 'experimental-catalog-governance' || lock.apiVersion !== 'agent-catalog.sudo.dev/v1alpha1'
    || JSON.stringify(Object.keys(lock.files ?? {}).sort()) !== JSON.stringify(Object.keys(files).sort())) throw new Error('Invalid catalog source identity')
  for (const [path, output] of Object.entries(files)) {
    if (lock.files[path]?.output !== output || !/^sha256:[a-f0-9]{64}$/.test(lock.files[path]?.digest ?? '')) throw new Error('Invalid catalog source file')
  }
}

export function renderCatalogFile(lock, path, source) {
  validateCatalogLock(lock)
  if (!Object.hasOwn(files, path)) throw new Error('Unknown catalog source path')
  if (`sha256:${sha256(source)}` !== lock.files[path].digest) throw new Error('Catalog source digest mismatch')
  if (source.includes('\r') || !source.endsWith('\n')) throw new Error('Owner source must use LF with a final newline')
  if (path.endsWith('.json')) {
    const schema = JSON.parse(source)
    if (schema.$schema !== 'http://json-schema.org/draft-07/schema#' || schema.$id !== 'https://contracts.sudo.dev/experimental/agent-catalog/v1alpha1') throw new Error('Invalid catalog schema identity')
    return source
  }
  return `// Derived from Moss ${lock.revision}:${path}. DO NOT EDIT.\n${source}`
}

export function generateCatalog(owner, check = false) {
  const lock = JSON.parse(readFileSync(join(root, 'source.lock.json'), 'utf8'))
  validateCatalogLock(lock)
  const prior = process.env.SUDOSTACK_REPOS_ROOT
  try {
    process.env.SUDOSTACK_REPOS_ROOT = dirname(resolve(owner))
    for (const [path, output] of Object.entries(files)) {
      const source = readLocalGitBlob({ ...lock, checkout: basename(resolve(owner)) }, path).toString('utf8')
      const result = renderCatalogFile(lock, path, source), target = join(root, output)
      if (check) {
        if (readFileSync(target, 'utf8') !== result) throw new Error(`Stale catalog artifact: ${output}`)
      } else writeFileSync(target, result)
    }
  } finally {
    if (prior === undefined) delete process.env.SUDOSTACK_REPOS_ROOT
    else process.env.SUDOSTACK_REPOS_ROOT = prior
  }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2), owner = args[args.indexOf('--owner') + 1]
  if (!args.includes('--owner') || !owner) throw new Error('Pass --owner <Moss checkout>; only the exact committed source is read')
  generateCatalog(owner, args.includes('--check'))
  console.log('Catalog schema/type sources and generated bytes verified')
}
